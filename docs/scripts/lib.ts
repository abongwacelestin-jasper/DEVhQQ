/**
 * Shared helpers for the docs generators and the link checker.
 *
 * Every script here runs with Node's strip-only TypeScript support, exactly
 * like the backend (`node --experimental-strip-types docs/scripts/<name>.ts`),
 * so the same syntax rules apply: no enums, no namespaces, no parameter
 * properties, `import type` for type-only imports.
 */

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Absolute path of the repository root (docs/scripts → ../..). */
export const ROOT = fileURLToPath(new URL('../../', import.meta.url));

export const rel = (abs: string) => relative(ROOT, abs);

/** True when the script was started with `--check` (verify, don't write). */
export const CHECK = process.argv.includes('--check');

/**
 * Writes a generated file, or in `--check` mode compares it with what is on
 * disk and exits non-zero when they differ. Generated files contain no
 * timestamps, so a clean tree always passes the check.
 */
export function emit(relPath: string, content: string): void {
  const abs = join(ROOT, relPath);
  const normalised = content.replace(/\n{3,}/g, '\n\n').replace(/\s*$/, '\n');
  if (CHECK) {
    const current = existsSync(abs) ? readFileSync(abs, 'utf8') : '';
    if (current !== normalised) {
      console.error(`✗ ${relPath} is stale — run \`npm run gen\` in docs/`);
      process.exitCode = 1;
      return;
    }
    console.log(`✓ ${relPath} is up to date`);
    return;
  }
  writeFileSync(abs, normalised);
  console.log(`wrote ${relPath}`);
}

/** Header placed at the top of every generated page. */
export function generatedBanner(script: string, sources: string[]): string {
  return [
    `<!-- GENERATED by docs/scripts/${script} — do not edit by hand. -->`,
    `<!-- Regenerate: cd docs && npm run gen   ·   Verify: cd docs && npm run check -->`,
    '',
    `> [!NOTE]`,
    `> This page is generated from ${sources.map((s) => `\`${s}\``).join(', ')} by`,
    `> [\`docs/scripts/${script}\`](../scripts/${script}). Edit the source, not this file.`,
    '',
  ].join('\n');
}

/** Recursively lists files under `dir` (absolute) whose name matches `test`. */
export function walk(dir: string, test: (name: string) => boolean, skip: string[] = []): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const abs = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
      if (skip.some((s) => abs === join(ROOT, s))) continue;
      out.push(...walk(abs, test, skip));
    } else if (test(entry.name)) {
      out.push(abs);
    }
  }
  return out.sort();
}

/** Escapes a value for use inside a Markdown table cell. */
export const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

// ── Static route-guard extraction ─────────────────────────────────────────
//
// The live route table (router.inventory()) knows method, path, summary, tag,
// auth mode and declared responses, but not which guards a route runs. The
// guards are visible in the source, so we read each `r.add(...)` call and pick
// out the middleware identifiers. This is a reader for this codebase's single
// registration style, not a TypeScript parser.

export interface RouteGuards {
  method: string;
  /** Path as written; `${x}` segments become a wildcard in `pattern`. */
  path: string;
  pattern: RegExp;
  file: string;
  line: number;
  areas: { area: string; level: string }[];
  stepUp: boolean;
  elevation: boolean;
  /** `authenticate` (full session) is in the chain. */
  session: boolean;
  partial: boolean;
  authLimited: boolean;
  /** `requireSession`: an interactive session, not a personal access token. */
  interactive: boolean;
  /** Route-specific middleware not covered above, by identifier. */
  other: string[];
}

/** Route-local middleware identifiers and how the reference labels them. */
const LOCAL_GUARDS: Record<string, string> = {
  accountLimiter: 'per-account rate limit',
  perMemberLimit: 'per-member rate limit',
  serviceOrAdmin: 'ML service HMAC, or Administration ≥ admin',
};

/** Returns the source text of the call whose `(` is at `open`, without the parens. */
function callArgs(src: string, open: number): string {
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    const ch = src[i];
    if (ch === "'" || ch === '"' || ch === '`') {
      // Skip a string literal (template expressions in this codebase are simple).
      const quote = ch;
      i++;
      while (i < src.length && src[i] !== quote) {
        if (src[i] === '\\') i++;
        i++;
      }
      continue;
    }
    if (ch === '/' && src[i + 1] === '/') {
      while (i < src.length && src[i] !== '\n') i++;
      continue;
    }
    if (ch === '(') depth++;
    if (ch === ')') {
      depth--;
      if (depth === 0) return src.slice(open + 1, i);
    }
  }
  return src.slice(open + 1);
}

export function readRouteGuards(): RouteGuards[] {
  const dir = join(ROOT, 'Backend/routes');
  const files = walk(dir, (n) => n.endsWith('.routes.ts'));
  const out: RouteGuards[] = [];
  for (const abs of files) {
    const src = readFileSync(abs, 'utf8');
    const re = /\br\.add\(/g;
    let m: RegExpExecArray | null;
    while ((m = re.exec(src))) {
      const args = callArgs(src, m.index + m[0].length - 1);
      const method = /^\s*'(GET|POST|PATCH|PUT|DELETE)'/.exec(args)?.[1];
      const path = /^\s*'[A-Z]+',\s*(['`])(\/[^'`]*)\1/.exec(args)?.[2];
      if (!method || !path) continue;
      const pattern = new RegExp(
        '^' +
          path
            .split(/\$\{[^}]+\}/)
            .map((s) => s.replace(/[.*+?^()|[\]\\]/g, '\\$&'))
            .join('[^/]+') +
          '$',
      );
      const areas = [...args.matchAll(/requireArea\(\s*'(\w+)',\s*'(\w+)'\s*\)/g)].map((a) => ({
        area: a[1],
        level: a[2],
      }));
      out.push({
        method,
        path,
        pattern,
        file: rel(abs),
        line: src.slice(0, m.index).split('\n').length,
        areas,
        stepUp: /\brequireStepUp\(/.test(args),
        elevation: /\brequireElevation\(/.test(args),
        session: /\bauthenticate\b|\bserviceOrAdmin\b/.test(args),
        partial: /\bauthenticatePartial\b/.test(args),
        authLimited: /\bauthLimiter\b/.test(args),
        interactive: /\brequireSession\b/.test(args),
        other: Object.keys(LOCAL_GUARDS).filter((k) => new RegExp(`\\b${k}\\b`).test(args)),
      });
    }
  }
  return out;
}

/** Path for display: template segments such as `${action}` become `<action>`. */
export const displayPath = (path: string) => path.replace(/\$\{(\w+)\}/g, '<$1>');

export function guardsFor(all: RouteGuards[], method: string, path: string) {
  return all.find((g) => g.method === method && (g.path === path || g.pattern.test(path)));
}

/** Short human label for a route's guards, e.g. "Deployment ≥ manage · step-up". */
export function guardLabel(g: RouteGuards | undefined): string {
  if (!g) return '—';
  const parts = g.areas.map((a) => `${a.area} ≥ ${a.level}`);
  if (g.stepUp) parts.push('step-up');
  if (g.elevation) parts.push('JIT elevation');
  if (g.interactive) parts.push('interactive session');
  for (const o of g.other) parts.push(LOCAL_GUARDS[o]);
  if (g.authLimited) parts.push('auth rate limit');
  return parts.length ? parts.join(' · ') : '—';
}
